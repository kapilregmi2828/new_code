a = {"name" : "kapil", "age": 25, "gender": "male"} # dictionary is unordered
print(a) # dictionary is mutable data type - (we can modify the dictionary after creation)
print(a["name"]) # access the value using key
print(a["age"]) # access the value using key
print(a.keys()) # keys() method is used to get all the keys from the dictionary
print(a.values()) # values() method is used to get all the values from the dictionary
print(a.items()) # items() method is used to get all the key-value pairs from the dictionary

